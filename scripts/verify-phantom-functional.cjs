const {chromium}=require('playwright');
const path=require('node:path'),{pathToFileURL}=require('node:url'),fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true}),page=await browser.newPage({viewport:{width:390,height:844}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(pathToFileURL(path.join(__dirname,'../dist/studio-review/index.html')).href);
 await page.waitForSelector('#ad-settings[open]');
 await page.locator('#city-mode').click();await page.waitForSelector('#ph-choice[open]');
 await page.locator('#ph-choice footer button').click();
 await page.locator('[data-studio-nav=frame]').click();
 await page.locator('#studio-width').fill('1024');await page.locator('#studio-height').fill('1024');await page.locator('#studio-height').blur();
 await page.waitForFunction(()=>document.querySelector('#studio-size-status').textContent==='已保存');
 const size=await page.evaluate(async()=>{const s=await __ADirectorApp.generationSettings();return {width:s.relay.width,height:s.relay.height};});
 if(size.width!==1024||size.height!==1024)throw Error('Size persistence '+JSON.stringify(size));
 await page.locator('[data-studio-nav=profiles]').click();await page.locator('.ad-profile-card').first().click();
 await page.locator('#ad-profile-name').fill('神崎 悠 · 验证');await page.locator('#ad-profile-save').click();
 await page.waitForFunction(()=>__ADirectorApp.snapshot().profiles.some(p=>p.name==='神崎 悠 · 验证'));
 await page.locator('#studio-global-back').click();
 await page.locator('[data-studio-nav=styles]').click();await page.locator('.ad-style-edit').first().click();
 const positive=page.locator('#ad-style-positive');
 await positive.fill('cinematic lighting, test');
 await page.locator('#ad-style-apply').click();
 await page.locator('[data-studio-nav=api]').click();
 await page.locator('#local-strength').fill('0.7');await page.locator('#local-strength').dispatchEvent('input');
 await page.locator('#local-motion-reset').click();
 if(await page.locator('#local-strength').inputValue()!=='0.65')throw Error('Motion reset');
 await page.locator('[data-studio-nav=settings]').click();await page.locator('#studio-service').click();
 await page.locator('#local-relay-url').fill('https://image.novelai.net/ai/generate-image');await page.locator('#local-relay-key').fill('local-test-placeholder');
 await page.locator('#local-relay-page [data-local-save]').click();
 await page.waitForFunction(()=>document.querySelector('#local-relay-key').value==='');
 await page.locator('#ad-settings-close').click();
 await page.evaluate(()=>__ADirectorUI.nextDialog?.('story_cg'));
 console.log('Size, profile save, style application, motion reset and API save passed');
 if(errors.length)throw Error(errors.join());
 fs.writeFileSync(path.join(__dirname,'../dist/phantom-check/functional.json'),JSON.stringify({passed:true,size,errors,actualModelCalls:0},null,2));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
